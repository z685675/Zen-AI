import * as z from 'zod'

export const HOTPATCH_FORMAT = 'zen-ai-hotpatch/1' as const
export const HOTPATCH_APP_ID = 'com.z685675.ZenAI' as const
export const HOTPATCH_ENTRIES = [
  'index.html',
  'miniWindow.html',
  'selectionToolbar.html',
  'selectionAction.html',
  'traceWindow.html'
] as const
export const HOTPATCH_LIMITS = {
  policyBytes: 256 * 1024,
  manifestBytes: 2 * 1024 * 1024,
  archiveBytes: 128 * 1024 * 1024,
  expandedBytes: 512 * 1024 * 1024,
  fileBytes: 64 * 1024 * 1024,
  fileCount: 10000,
  policyLifetimeSeconds: 7 * 24 * 60 * 60,
  clockSkewSeconds: 300
} as const

const hash = z.string().regex(/^[a-f0-9]{64}$/)
const identifier = z.string().regex(/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,95}$/)
const integer = z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER)

/** Exact compatibility, not a loose version range. This object is generated by the base build. */
export const hotpatchBaseSchema = z
  .object({
    appId: z.literal(HOTPATCH_APP_ID),
    version: z.string().regex(/^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.-]+)?$/),
    baseBuildId: hash,
    baseCommit: z.string().regex(/^[a-f0-9]{40}$/),
    platform: z.enum(['win32', 'darwin', 'linux']),
    arch: z.enum(['x64', 'arm64']),
    channel: identifier,
    packaging: z.enum(['installed', 'portable', 'development']),
    mainFingerprint: hash,
    preloadFingerprint: hash,
    runtimeFingerprint: hash,
    contractsFingerprint: hash,
    securityFingerprint: hash
  })
  .strict()
export type HotpatchBase = z.infer<typeof hotpatchBaseSchema>

export const hotpatchFileSchema = z
  .object({
    path: z.string().min(1).max(512),
    size: integer.max(HOTPATCH_LIMITS.fileBytes),
    sha256: hash
  })
  .strict()
export type HotpatchFile = z.infer<typeof hotpatchFileSchema>

export const hotpatchArtifactSchema = z
  .object({
    schemaVersion: z.literal(1),
    patchId: identifier,
    base: hotpatchBaseSchema,
    sourceCommit: z.string().regex(/^[a-f0-9]{40}$/),
    createdAt: integer,
    notes: z.string().max(4000),
    archive: z
      .object({
        url: z.string().url().max(2048),
        sha256: hash,
        size: integer.positive().max(HOTPATCH_LIMITS.archiveBytes)
      })
      .strict(),
    expandedSize: integer.max(HOTPATCH_LIMITS.expandedBytes),
    files: z.array(hotpatchFileSchema).min(HOTPATCH_ENTRIES.length).max(HOTPATCH_LIMITS.fileCount)
  })
  .strict()
export type HotpatchArtifact = z.infer<typeof hotpatchArtifactSchema>

export const hotpatchPolicySchema = z
  .object({
    schemaVersion: z.literal(1),
    base: hotpatchBaseSchema,
    policySequence: integer.positive(),
    issuedAt: integer,
    expiresAt: integer,
    action: z.enum(['offer', 'pause', 'rollback']),
    target: z
      .object({
        patchId: identifier,
        manifestUrl: z.string().url().max(2048),
        manifestSha256: hash
      })
      .strict()
      .nullable(),
    rollout: z
      .object({
        basisPoints: integer.max(10000),
        salt: identifier,
        testCodeHashes: z.array(hash).max(100)
      })
      .strict()
  })
  .strict()
export type HotpatchPolicy = z.infer<typeof hotpatchPolicySchema>

/** payload is base64url of the exact UTF-8 JSON bytes; never reserialize before verifying. */
export const hotpatchEnvelopeSchema = z
  .object({
    format: z.literal(HOTPATCH_FORMAT),
    kind: z.enum(['artifact', 'policy']),
    keyId: identifier,
    payload: z
      .string()
      .regex(/^[a-zA-Z0-9_-]+$/)
      .max(Math.ceil((HOTPATCH_LIMITS.manifestBytes * 4) / 3)),
    signature: z.string().regex(/^[a-zA-Z0-9_-]{86}$/)
  })
  .strict()
export type HotpatchEnvelope = z.infer<typeof hotpatchEnvelopeSchema>

export type HotpatchErrorCode =
  | 'signature'
  | 'schema'
  | 'compatibility'
  | 'policy-replay'
  | 'policy-time'
  | 'url'
  | 'network'
  | 'size'
  | 'integrity'
  | 'archive'
  | 'path'
  | 'storage'
  | 'startup'
  | 'disabled'

export class HotpatchError extends Error {
  constructor(
    public readonly code: HotpatchErrorCode,
    message: string
  ) {
    super(message)
    this.name = 'HotpatchError'
  }
}

export const HOTPATCH_IPC = {
  status: 'hotpatch:status',
  startup: 'hotpatch:startup',
  healthy: 'hotpatch:healthy',
  check: 'hotpatch:check',
  disable: 'hotpatch:disable',
  enable: 'hotpatch:enable'
} as const
export interface HotpatchStatus {
  baseVersion: string
  baseBuildId?: string
  enabled: boolean
  status: 'unavailable' | 'builtin' | 'active' | 'checking' | 'pending' | 'recovering' | 'disabled'
  patchId?: string
  pendingPatchId?: string
  policySequence: number
  startup: 'builtin' | 'checking' | 'healthy' | 'failed'
  lastError?: { code: string; at: number }
}
