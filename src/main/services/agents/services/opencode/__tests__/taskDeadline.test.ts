import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { createTaskDeadline } from '../taskDeadline'

beforeEach(() => vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'performance'] }))
afterEach(() => vi.useRealTimers())
describe('execution and bounded human wait budgets', () => {
  it('retains remaining execution budget across a long permission wait', () => {
    const timeout = vi.fn()
    const deadline = createTaskDeadline(timeout, 1000, 3000)
    vi.advanceTimersByTime(700)
    deadline.wait('permission:1')
    vi.advanceTimersByTime(2500)
    expect(timeout).not.toHaveBeenCalled()
    deadline.continue('permission:1')
    vi.advanceTimersByTime(299)
    expect(timeout).not.toHaveBeenCalled()
    vi.advanceTimersByTime(1)
    expect(timeout).toHaveBeenCalledExactlyOnceWith('execution')
    deadline.dispose()
  })
  it('counts overlapping browser and permission waits once and waits for both', () => {
    const timeout = vi.fn()
    const deadline = createTaskDeadline(timeout, 1000, 3000)
    deadline.wait('browser:1')
    deadline.wait('browser:1')
    deadline.wait('permission:1')
    vi.advanceTimersByTime(1500)
    deadline.continue('permission:1')
    expect(deadline.waiting).toBe(true)
    vi.advanceTimersByTime(1000)
    deadline.continue('browser:1')
    expect(deadline.waiting).toBe(false)
    vi.advanceTimersByTime(999)
    expect(timeout).not.toHaveBeenCalled()
    deadline.dispose()
    vi.advanceTimersByTime(10000)
    expect(timeout).not.toHaveBeenCalled()
  })
  it('does not reset the cumulative human wait budget with repeated authorizations', () => {
    const timeout = vi.fn()
    const deadline = createTaskDeadline(timeout, 1000, 3000)
    deadline.wait('first')
    vi.advanceTimersByTime(2000)
    deadline.continue('first')
    vi.advanceTimersByTime(100)
    deadline.wait('second')
    vi.advanceTimersByTime(1000)
    expect(timeout).toHaveBeenCalledExactlyOnceWith('human-wait')
    deadline.continue('second')
    vi.advanceTimersByTime(10000)
    expect(timeout).toHaveBeenCalledOnce()
    deadline.dispose()
  })
})
